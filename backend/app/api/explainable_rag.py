
from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy.orm import Session

from app.database import SessionLocal
from app.models.regulatory_change import RegulatoryChange

from app.services.impact_engine_service import (
    get_impact_engine_service,
)

from app.services.explainable_rag_service import (
    ExplainableRAGService,
)


router = APIRouter(
    prefix="/explainable-rag",
    tags=["Explainable RAG"],
)

explanation_service = ExplainableRAGService()


def get_db():
    db = SessionLocal()

    try:
        yield db
    finally:
        db.close()


@router.get("/health")

@router.get("/health")
def explainable_rag_health():
    return {
        "status": "configured",
        "service": "Explainable RAG",
        "provider": "Rule-based",
        "llm_required": False,
    }



@router.get("/regulatory-changes/{regulatory_change_id}")
def explain_regulatory_change(
    regulatory_change_id: str,
    top_k: int = Query(default=10, ge=1, le=50),
    legal_top_k: int = Query(default=5, ge=1, le=20),
    policy_evidence_top_k: int = Query(
        default=3,
        ge=1,
        le=10,
    ),
    db: Session = Depends(get_db),
):
    """
    Run the existing impact engine and add evidence-grounded
    explanations generated by Ollama.
    """

    regulatory_change = (
        db.query(RegulatoryChange)
        .filter(
            RegulatoryChange.regulatory_change_id
            == regulatory_change_id
        )
        .first()
    )

    if regulatory_change is None:
        raise HTTPException(
            status_code=404,
            detail=(
                f"Regulatory change "
                f"'{regulatory_change_id}' not found."
            ),
        )

    try:
        impact_service = get_impact_engine_service()

        impact_result = impact_service.analyze_regulatory_change(
            db=db,
            regulatory_change=regulatory_change,
            top_k=top_k,
            legal_top_k=legal_top_k,
            policy_evidence_top_k=policy_evidence_top_k,
        )

        return explanation_service.explain(impact_result)

    except RuntimeError as exc:
        # Most commonly an Ollama connectivity or generation error.
        raise HTTPException(
            status_code=503,
            detail=f"Explainable RAG could not generate an explanation: {exc}",
        ) from exc

    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=(
                "Explainable RAG analysis failed. "
                "Check the backend logs for details."
            ),
        ) from exc
